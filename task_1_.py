import pandas as pd
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

"""This loads pandas for tables, and scikit-learn for the TF-IDF and similarity maths. Nothing prints."""

df = pd.read_csv("Dataset.csv")
print(df.shape)
df.head()

"""You should see (8790, 10) and a table of the first 4 titles."""

df.info()
print(df["type"].value_counts())
print((df == "Not Given").sum())

"""This shows that missing values are written as the text “Not Given” (2,588 directors, 287 countries)"""

df = df.replace("Not Given", "")
df = df.drop_duplicates(subset=["title", "type", "release_year"]).reset_index(drop=True)
print(df.shape)

"""This blanks out the placeholders and removes 3 duplicate rows. You should see (8787, 10).

"""

def clean_list(text):
    return " ".join(t.strip().lower().replace(" ", "_") for t in text.split(",") if t.strip())

df["genres_t"]   = df["listed_in"].apply(clean_list)
df["director_t"] = df["director"].apply(clean_list)
df["country_t"]  = df["country"].apply(clean_list)
df["type_t"]     = df["type"].apply(clean_list)
df["rating_t"]   = df["rating"].apply(clean_list)    # new column, original kept

GENRE_WEIGHT = 3     # how many times genres are repeated; try 3 later

df["soup"] = ((df["genres_t"] + " ").str.repeat(GENRE_WEIGHT)
              + df["director_t"] + " "
              + df["country_t"] + " "
              + df["type_t"] + " "
              + df["rating_t"])

df[["title", "rating", "soup"]].head()

"""Each title now has one line of text describing it."""

tfidf = TfidfVectorizer(token_pattern=r"\S+")
matrix = tfidf.fit_transform(df["soup"])
print(matrix.shape)
print([f for f in tfidf.get_feature_names_out() if f in ("r", "g", "tv-ma", "pg-13")])

"""Each title becomes a row of numbers, like the A, B and C table from my last message. Rare words such as a specific director get more weight than common ones."""

def recommend(title, n=10):
    matches = df.index[df["title"].str.lower() == title.lower()]
    if len(matches) == 0:
        return "Title not found"
    i = matches[0]
    scores = cosine_similarity(matrix[i], matrix).ravel()
    scores[i] = -1                       # don't recommend the title itself
    top = scores.argsort()[::-1][:n]     # indexes of the n highest scores
    result = df.loc[top, ["title", "type", "listed_in", "release_year"]].copy()
    result["similarity"] = scores[top].round(3)
    return result

recommend("Narcos")

"""this will recommend show that are closely related or similar"""

genre_sets = df["listed_in"].apply(lambda s: set(g.strip() for g in s.split(",")))
sample = np.random.RandomState(42).choice(len(df), 300, replace=False)

hits = []
for i in sample:
    scores = cosine_similarity(matrix[i], matrix).ravel()
    scores[i] = -1
    for j in scores.argsort()[::-1][:10]:
        hits.append(len(genre_sets[i] & genre_sets[j]) > 0)
print("Recommendations sharing a genre:", round(np.mean(hits), 3))

rng = np.random.RandomState(0)
rand_hits = [len(genre_sets[i] & genre_sets[j]) > 0
             for i in sample for j in rng.choice(len(df), 10, replace=False)]
print("Random picks sharing a genre:  ", round(np.mean(rand_hits), 3))

"""The model score is high partly because genres are in the features, so it isn’t a perfect test, but it proves the system works better than random."""